#!/usr/bin/env node
/**
 * Regenerate src/api/generated/schema.ts from src/api/openapi.json (the subset of the Ant0
 * desktop local API that this adapter calls).
 *
 *   node scripts/generate-api.mjs           # write
 *   node scripts/generate-api.mjs --check   # exit 1 if the committed file is stale
 */
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";
import * as prettier from "prettier";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const spec = join(root, "src/api/openapi.json");
const out = join(root, "src/api/generated/schema.ts");
const HEADER =
  "/**\n * This file was auto-generated by openapi-typescript (scripts/generate-api.mjs).\n" +
  " * Do not make direct changes to the file; run `pnpm generate:api`.\n */\n\n";

const ast = await openapiTS(JSON.parse(readFileSync(spec, "utf8")));
const config = (await prettier.resolveConfig(out)) ?? {};
const text = await prettier.format(HEADER + astToString(ast), { ...config, parser: "typescript" });
if (process.argv.includes("--check")) {
  if (!existsSync(out) || readFileSync(out, "utf8") !== text) {
    console.error("src/api/generated/schema.ts is stale; run pnpm generate:api");
    process.exit(1);
  }
} else {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, text);
}
